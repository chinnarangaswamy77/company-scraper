// Helper to generate a realistic list of 1000 companies using cities and suffixes
export function generate1000Companies(): string[] {
  const list = [...REAL_COMPANIES];
  
  const cities = [
    "Bengaluru", "Hyderabad", "Pune", "Chennai", "Mumbai", 
    "Noida", "Gurugram", "Kochi", "Trivandrum", "Coimbatore", 
    "Ahmedabad", "Kolkata", "Jaipur", "Indore", "Bhubaneswar",
    "Mangaluru", "Mysuru", "Nagpur", "Nashik", "Visakhapatnam"
  ];
  
  const stems = [
    "Apex", "Nova", "Quantum", "Synergy", "Matrix", 
    "Zenith", "Cloud", "Infra", "Core", "Vanguard", 
    "Trident", "Delta", "Nexus", "Sigma", "Vector", 
    "Optima", "Vertex", "Summit", "Horizon", "Ascent",
    "Velocity", "Helix", "Stellar", "Pinnacle", "Aegis",
    "Intellect", "Krypton", "Crest", "Titan", "Beacon",
    "Omni", "Enigma", "Cognitive", "Evolve", "Dynamic",
    "Fluent", "Adaptive", "Catalyst", "Integra", "Aura",
    "Clarity", "Vivid", "Prism", "Beacon", "Radiant"
  ];

  const suffixes = [
    "Software", "Technologies", "Solutions", "IT Services", 
    "Digital Systems", "Tech Labs", "Consulting", "Systems", 
    "Infotech", "Innovation Hub", "Cloud Services", "Data Analytics"
  ];

  let stemIndex = 0;
  let cityIndex = 0;
  let suffixIndex = 0;

  while (list.length < 1000) {
    const stem = stems[stemIndex % stems.length];
    const city = cities[cityIndex % cities.length];
    const suffix = suffixes[suffixIndex % suffixes.length];
    
    // Generate name formats:
    // 1. Stem City Suffix (e.g., Apex Bengaluru Technologies)
    // 2. City Stem Suffix (e.g., Bengaluru Nova Solutions)
    // 3. Stem Suffix India (e.g., Quantum Software India)
    let companyName = "";
    const selector = (stemIndex + cityIndex + suffixIndex) % 3;
    
    if (selector === 0) {
      companyName = `${stem} ${city} ${suffix}`;
    } else if (selector === 1) {
      companyName = `${city} ${stem} ${suffix}`;
    } else {
      companyName = `${stem} ${suffix} India`;
    }

    if (!list.includes(companyName)) {
      list.push(companyName);
    }

    stemIndex++;
    if (stemIndex % stems.length === 0) {
      cityIndex++;
      if (cityIndex % cities.length === 0) {
        suffixIndex++;
      }
    }
  }

  return list.slice(0, 1000);
}

export const DEFAULT_COMPANIES = generate1000Companies();
